"""Bundle the native desktop client deterministically, without npm dependencies.

The view has one explicit ESM export and no imports. Harness supplies React;
all page code and scoped CSS stay in its lazy module factory. --check lets CI
detect a stale shipped bundle instead of silently publishing old UI code.
"""

import argparse
import json
from pathlib import Path


def bundle(root=None, *, check=False):
    root = Path(root) if root else Path(__file__).resolve().parents[1]
    plugin = root / "integrations" / "deepseek-harness"
    source = plugin / "desktop"
    view = (source / "view.js").read_text(encoding="utf-8")
    marker = "export function mountDesktop("
    if view.count(marker) != 1:
        raise ValueError("Desktop view must have exactly one mountDesktop export")
    view = view.replace(marker, "function mountDesktop(", 1)
    css = (source / "view.css").read_text(encoding="utf-8")
    template = (source / "client-entry.js").read_text(encoding="utf-8")
    result = "// Generated by scripts/build_native_client.py. Edit desktop/ sources.\n" + template.replace(
        "__MEMORYDREAMING_CSS__", json.dumps(css, ensure_ascii=False)
    ).replace("/* MEMORYDREAMING_VIEW */", view)
    target = plugin / "lib" / "client.js"
    if check:
        if not target.is_file() or target.read_text(encoding="utf-8") != result:
            raise ValueError("Native client bundle is stale; run python scripts/build_native_client.py")
    else:
        target.write_text(result, encoding="utf-8", newline="\n")
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(bundle(check=parser.parse_args().check))
